export type MsgKey = keyof typeof dict;

/** 取当前语言的文案；在组件里调用时会随 app.lang 响应式更新。 */
export function t(key: MsgKey | (string & {}), params?: Record<string, string | number>): string {
  const entry = (dict as Record<string, [string, string]>)[key];
  let s = entry ? entry[app.lang === "zh" ? 0 : 1] : key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** 追加文案（各页面模块在自己的文件里注册，避免这个文件无限增长）。 */
export function extend(entries: Record<string, [string, string]>) {
  Object.assign(dict, entries);
}
