//! schema 快照（`platform-and-ops.md` §9「CI 校验 schema 快照」）：执行全部迁移后，把 PostgreSQL 与 ClickHouse 的
//! 结构生成规范化文本，与提交的 `schema/postgres.sql`、`schema/clickhouse.sql` 比对，不一致即失败。
//! 设 `RIVU_SCHEMA_UPDATE=1` 重新生成这两个文件（结构有意变化时，与迁移一起提交）。
//!
//! 不依赖 `pg_dump`：从系统目录读表、列、约束、索引、触发器与函数，按名字排序。ClickHouse 用 `SHOW CREATE`，
//! 库名换成 `{{database}}`（与迁移文件的写法一致）。快照是「迁移后的结果」的描述，不是可执行的 SQL。
//!
//! 需要 `RIVU_TEST_DATABASE_URL` 与 `RIVU_TEST_CLICKHOUSE_URL`；缺少时跳过。开发库与 CI 都是同一套迁移建出来的；
//! 开发库里的旧结构若与新迁移不符（迁移就地改过而库没重建），先重建开发库再比对。

use std::fmt::Write as _;
use std::path::PathBuf;

use clickhouse::Client;
use rivu::migrate;
use rivu_common::config::{ChAccount, Config, Env, Role, Secret};
use sqlx::{PgPool, Row};

fn var(name: &str) -> Option<String> {
    std::env::var(name).ok().filter(|v| !v.is_empty())
}

fn migrator() -> ChAccount {
    ChAccount {
        user: var("RIVU_TEST_CH_MIGRATOR_USER").unwrap_or_else(|| "rivu_migrator".into()),
        password: Secret::new(
            var("RIVU_TEST_CH_MIGRATOR_PASSWORD").unwrap_or_else(|| "rivu_dev_migrator".into()),
        ),
    }
}

fn snapshot_path(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../schema")
        .join(name)
}

/// PostgreSQL 的规范化结构（`public` 模式，不含 sqlx 的迁移记录表）。
async fn pg_schema(pg: &PgPool) -> String {
    let mut out = String::from(
        "-- 由 bin/rivu/tests/schema_snapshot.rs 生成（RIVU_SCHEMA_UPDATE=1），不要手工编辑。\n\
         -- 迁移后 PostgreSQL public 模式的结构：表（列、约束、索引、触发器）与函数，按名字排序。\n",
    );
    let tables: Vec<String> = sqlx::query_scalar(
        "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND c.relname <> '_sqlx_migrations'
         ORDER BY c.relname",
    )
    .fetch_all(pg)
    .await
    .unwrap();
    for t in &tables {
        let _ = writeln!(out, "\nTABLE {t}");
        let cols = sqlx::query(
            "SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS ty, a.attnotnull,
                    pg_get_expr(d.adbin, d.adrelid) AS def, a.attidentity::text AS ident,
                    a.attgenerated::text AS gen
             FROM pg_attribute a
             LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
             WHERE a.attrelid = ('public.' || quote_ident($1))::regclass AND a.attnum > 0 AND NOT a.attisdropped
             ORDER BY a.attnum",
        )
        .bind(t)
        .fetch_all(pg)
        .await
        .unwrap();
        for c in cols {
            let name: String = c.get("attname");
            let ty: String = c.get("ty");
            let mut line = format!("  {name} {ty}");
            if c.get::<bool, _>("attnotnull") {
                line.push_str(" NOT NULL");
            }
            match c.get::<String, _>("ident").as_str() {
                "a" => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
                "d" => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
                _ => {}
            }
            if let Some(def) = c.get::<Option<String>, _>("def") {
                if c.get::<String, _>("gen") == "s" {
                    let _ = write!(line, " GENERATED ALWAYS AS ({def}) STORED");
                } else {
                    let _ = write!(line, " DEFAULT {def}");
                }
            }
            let _ = writeln!(out, "{line}");
        }
        let cons = sqlx::query(
            // NOT NULL 已在列上（PG 18 起它们也是有名字的约束，排除以免随 PG 版本变化）
            "SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint
             WHERE conrelid = ('public.' || quote_ident($1))::regclass AND contype <> 'n'
             ORDER BY conname",
        )
        .bind(t)
        .fetch_all(pg)
        .await
        .unwrap();
        for c in cons {
            let _ = writeln!(
                out,
                "  CONSTRAINT {} {}",
                c.get::<String, _>("conname"),
                c.get::<String, _>("def")
            );
        }
        // 约束自带的索引（主键、唯一约束）已由约束描述，不重复
        let idx: Vec<String> = sqlx::query_scalar(
            "SELECT pg_get_indexdef(i.indexrelid) FROM pg_index i
             JOIN pg_class ic ON ic.oid = i.indexrelid
             WHERE i.indrelid = ('public.' || quote_ident($1))::regclass
               AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.indexrelid)
             ORDER BY ic.relname",
        )
        .bind(t)
        .fetch_all(pg)
        .await
        .unwrap();
        for i in idx {
            let _ = writeln!(out, "  {i}");
        }
        let trg: Vec<String> = sqlx::query_scalar(
            "SELECT pg_get_triggerdef(oid) FROM pg_trigger
             WHERE tgrelid = ('public.' || quote_ident($1))::regclass AND NOT tgisinternal
             ORDER BY tgname",
        )
        .bind(t)
        .fetch_all(pg)
        .await
        .unwrap();
        for tr in trg {
            let _ = writeln!(out, "  {tr}");
        }
    }
    // 扩展（如 citext）自带的函数与聚合不算迁移的产物：只列扩展名
    let exts: Vec<String> = sqlx::query_scalar(
        "SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY extname",
    )
    .fetch_all(pg)
    .await
    .unwrap();
    for e in exts {
        let _ = write!(out, "\nEXTENSION {e}\n");
    }
    let funcs: Vec<String> = sqlx::query_scalar(
        "SELECT pg_get_functiondef(p.oid) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
         WHERE n.nspname = 'public' AND p.prokind = 'f'
           AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass
                           AND d.objid = p.oid AND d.deptype = 'e')
         ORDER BY p.proname, pg_get_function_identity_arguments(p.oid)",
    )
    .fetch_all(pg)
    .await
    .unwrap();
    for f in funcs {
        let _ = write!(out, "\n{}", f.trim_end());
        out.push('\n');
    }
    out
}

/// ClickHouse 的规范化结构：库里的全部表与视图的 `SHOW CREATE`，按名字排序，库名换成 `{{database}}`。
async fn ch_schema(ch: &Client, database: &str) -> String {
    let mut out = String::from(
        "-- 由 bin/rivu/tests/schema_snapshot.rs 生成（RIVU_SCHEMA_UPDATE=1），不要手工编辑。\n\
         -- 迁移后 ClickHouse 库的结构：每张表与视图的 SHOW CREATE，按名字排序，库名写作 {{database}}。\n",
    );
    let names: Vec<String> = ch
        .query("SELECT name FROM system.tables WHERE database = {db:String} ORDER BY name")
        .param("db", database)
        .fetch_all()
        .await
        .unwrap();
    for n in names {
        let ddl: String = ch
            .query(&format!("SHOW CREATE TABLE `{database}`.`{n}`"))
            .fetch_one()
            .await
            .unwrap();
        let ddl = ddl.replace(&format!("{database}."), "{{database}}.");
        let _ = write!(out, "\n{};\n", ddl.trim_end());
    }
    out
}

fn compare(name: &str, actual: &str) -> Option<String> {
    let path = snapshot_path(name);
    if var("RIVU_SCHEMA_UPDATE").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, actual).unwrap();
        println!("已写入 {}", path.display());
        return None;
    }
    let expected = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    if expected == actual {
        return None;
    }
    // 报告第一处不同的行，方便定位
    let (mut e, mut a) = (expected.lines(), actual.lines());
    let mut line = 1;
    loop {
        match (e.next(), a.next()) {
            (Some(x), Some(y)) if x == y => line += 1,
            (x, y) => {
                return Some(format!(
                    "schema/{name} 与迁移后的结构不一致（第 {line} 行）：\n  快照：{}\n  实际：{}\n\
                     结构有意变化时用 RIVU_SCHEMA_UPDATE=1 重新生成并与迁移一起提交",
                    x.unwrap_or("<结束>"),
                    y.unwrap_or("<结束>")
                ));
            }
        }
    }
}

#[tokio::test]
async fn migrated_schema_matches_the_committed_snapshot() {
    let (Some(pg_url), Some(ch_url)) = (
        var("RIVU_TEST_DATABASE_URL"),
        var("RIVU_TEST_CLICKHOUSE_URL"),
    ) else {
        println!("跳过：需要设置 RIVU_TEST_DATABASE_URL 和 RIVU_TEST_CLICKHOUSE_URL");
        return;
    };
    let database = var("RIVU_TEST_CH_DATABASE").unwrap_or_else(|| "rivu".into());
    let account = migrator();
    let cfg_env = Env::from_pairs([
        ("RIVU_DATABASE_URL", pg_url.as_str()),
        ("RIVU_CLICKHOUSE_URL", ch_url.as_str()),
        ("RIVU_CH_DATABASE", database.as_str()),
        ("RIVU_CH_MIGRATOR_USER", account.user.as_str()),
        ("RIVU_CH_MIGRATOR_PASSWORD", account.password.expose()),
    ]);
    let config = Config::from_env(Role::Migrate, &cfg_env).expect("测试配置");
    migrate::apply(&config, false).await.expect("migrate");

    let pg = rivu_storage_pg::connect(&pg_url, 2).await.expect("连接 PG");
    let ch = rivu_storage_ch::client(&ch_url, &account, None);
    let problems: Vec<String> = [
        compare("postgres.sql", &pg_schema(&pg).await),
        compare("clickhouse.sql", &ch_schema(&ch, &database).await),
    ]
    .into_iter()
    .flatten()
    .collect();
    assert!(problems.is_empty(), "{}", problems.join("\n\n"));
}
